function buildMarkdown(sample) {
    const esc = (v) => String(v === undefined || v === null ? '' : v).replace(/\|/g, '\\|');
    const lines = [
        '# Сводная таблица анкеты — структура и правила',
        '',
        'Таблица приходит письмом во вложении `Анкета_ФИО.xlsx`, лист **«Сводная»**.',
        `Всего колонок: **${COLUMNS.length}**. Порядок и состав колонок постоянны:`,
        'если данных нет, ячейка остаётся пустой, но сама колонка из таблицы не исчезает —',
        'так строку можно без переделок вставлять в свою базу.',
        '',
        'Второй лист файла — **«Протоколы»**: по строке на каждую литеру.',
        'Он не входит в 52 колонки и нужен для автоматической обработки.',
        '',
    ];

    BLOCKS.forEach((block) => {
        lines.push(`## ${block.title}  (К${block.from}–К${block.to})`);
        lines.push('');
        lines.push(`_${block.note}_`);
        lines.push('');
        lines.push('| № | Заголовок | Откуда берётся | Что попадает в ячейку | Когда пусто |');
        lines.push('|---|---|---|---|---|');
        COLUMNS.filter((c) => c.n >= block.from && c.n <= block.to).forEach((col) => {
            const doc = docFor(col);
            lines.push(`| К${col.n} | ${esc(col.header)} | ${esc(doc.source)} | ${esc(doc.rule)} | ${esc(doc.empty)} |`);
        });
        lines.push('');
    });

    lines.push('## Возможные значения');
    lines.push('');
    lines.push('| № | Заголовок | Значения | Пример |');
    lines.push('|---|---|---|---|');
    COLUMNS.forEach((col) => {
        const doc = docFor(col);
        lines.push(`| К${col.n} | ${esc(col.header)} | ${esc(doc.values)} | ${esc(sample[col.key] || '—')} |`);
    });
    lines.push('');

    lines.push('## Как считаются последние шесть колонок');
    lines.push('');
    lines.push('### К47 Высота и К48 ОЗП');
    lines.push('');
    lines.push('| Что отметил работник | В таблице |');
    lines.push('|---|---|');
    lines.push('| Буду выполнять работы | 2 гр. |');
    lines.push('| Буду согласовывать документы или войду в комиссию | 3 гр. |');
    lines.push('| И то, и другое | 2, 3 гр. |');
    lines.push('| Не работаю | не требуется |');
    lines.push('');
    lines.push('### К49 Электробезопасность');
    lines.push('');
    lines.push('| Ответ в анкете | В таблице |');
    lines.push('|---|---|');
    lines.push('| Не нужно по моей работе | не требуется |');
    lines.push('| Удостоверения нет, но нужно | Требуется |');
    lines.push('| Есть действующее удостоверение | требуется + имеется с предыдущего места работы (III группа) |');
    lines.push('');
    lines.push('### К50 Промышленная безопасность');
    lines.push('');
    lines.push('| Ответ в анкете | В таблице |');
    lines.push('|---|---|');
    lines.push('| Не нужно по моей работе | не требуется |');
    lines.push('| Удостоверения нет, но нужно | Требуется |');
    lines.push('| Есть удостоверение | имеется с предыдущего места работы (перечень литер), действ. N дней |');
    lines.push('| Есть удостоверение, срок вышел | …, ПРОСРОЧЕН на N дней |');
    lines.push('');
    lines.push('Аттестация действует **5 лет** с даты протокола. Литеры собираются из всех протоколов без повторов.');
    lines.push('Если протоколов несколько, срок считается по тому, который истекает раньше остальных.');
    lines.push('');
    lines.push('### К51 Группа В');
    lines.push('');
    lines.push('Программа «В» — работы повышенной опасности. Назначается, если выполнено хотя бы одно условие:');
    lines.push('');
    lines.push('- отдел **CM** (строительный) или **HSES** (охрана труда);');
    lines.push('- отмечены работы на высоте;');
    lines.push('- отмечены работы в замкнутом пространстве;');
    lines.push('- нужна электробезопасность;');
    lines.push('- нужна промышленная безопасность.');
    lines.push('');
    lines.push('В скобках перечисляется, что именно сработало: `Требуется (CM, высота, ОЗП, ЭБ, ПБ)`.');
    lines.push('Если не сработало ничего — ячейка пустая.');
    lines.push('');
    lines.push('### К52 SVP');
    lines.push('');
    lines.push('Прямо отражает ответ по управлению транспортом: `требуется` или `не требуется`.');
    lines.push('');

    lines.push('## Что важно помнить');
    lines.push('');
    lines.push('- **К13 «СНИЛС»** — общая колонка для всех идентификаторов. У россиянина здесь СНИЛС, у казахстанца ИИН, у белоруса личный номер. Что именно лежит в ячейке, показывает К14 «Гражданство».');
    lines.push('- **К15 «Телефон»** — если работник указал несколько номеров, все они в одной ячейке через `;`.');
    lines.push('- **Паспорт (К18–К21)** спрашивается, только когда нужна промышленная безопасность или электробезопасность. В остальных случаях эти четыре колонки пустые.');
    lines.push('- **Код подразделения (К21)** есть только у российского паспорта. У Казахстана и Беларуси поле не показывается вовсе.');
    lines.push('- **Протоколов помещается 5**, обучений — тоже 5. Если у работника больше, лишнее он приносит в отдел охраны труда.');
    lines.push('- **Ответ «Пока не знаю»** не даёт отправить анкету — такие строки в таблицу не попадают в принципе.');
    lines.push('- **Раздел «Другие обучения» необязательный**: пустые строки не попадают ни в письмо, ни в таблицу.');
    lines.push('');

    return lines.join('\n');
}

