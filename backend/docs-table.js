/** Для колонок протоколов и обучений пояснения строятся по шаблону */
function docFor(col) {
  if (DOCS[col.key]) return DOCS[col.key];

  const protocol = /^protocol(\d+)(Number|Areas|Date)$/.exec(col.key);
  if (protocol) {
    const n = protocol[1];
    const base = {
      source: `Анкета → Промышленная безопасность → Протокол ${n}`,
      empty: `Если протоколов меньше ${n} или удостоверения нет — колонка остаётся пустой, но из таблицы не исчезает`,
    };
    if (protocol[2] === 'Number') {
      return {
        ...base,
        rule: 'Номер протокола и место сдачи в одной ячейке. Место сдачи работник выбирает обязательно.',
        values: '24-15-1234 (РТН) · 24-15-9999 (ЕПТ)',
      };
    }
    if (protocol[2] === 'Areas') {
      return {
        ...base,
        rule: 'Области аттестации из этого протокола через запятую. Работник выбирает их из справочника Ростехнадзора, вручную вписать нельзя.',
        values: 'А.1, Б.8.3',
      };
    }
    return { ...base, rule: 'Дата протокола. От неё считается срок действия в колонке К50.', values: '10.01.2024' };
  }

  const training = /^training(\d+)$/.exec(col.key);
  if (training) {
    return { ...DOCS.training, source: `Анкета → Другие обучения → обучение ${training[1]}` };
  }

  return { source: '', rule: '', values: '', empty: '' };
}

